<#
.SYNOPSIS
  POC P0: generate a Revit journal that opens a Dynamo graph in MANUAL mode (no Run).
  UNVERIFIED: not yet run against Revit 2025 / Dynamo 3.3.2. Run it on Windows and report results.

.DESCRIPTION
  Read-only toward the repo and any model: it only writes one journal file under
  %LOCALAPPDATA%\DynamoToolbox\journals. It starts Revit ONLY when -Launch is given
  and no Revit 2025 process is already running.

.EXAMPLE
  .\New-DynamoJournal.ps1 -ToolId excel-sync            # generate journal only, print path
  .\New-DynamoJournal.ps1 -ToolId excel-sync -Launch    # generate and start Revit 2025
#>
[CmdletBinding()]
param(
  [Parameter(Mandatory)][string]$ToolId,
  [string]$Template,            # optional .rte; auto-detected under ProgramData if omitted
  [switch]$SkipTemplate,        # variant: journal without opening a template first
  [switch]$Launch
)
$ErrorActionPreference = 'Stop'

$root  = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$tools = (Get-Content -Raw -Encoding UTF8 (Join-Path $PSScriptRoot '..\tools.json') | ConvertFrom-Json).tools
$tool  = $tools | Where-Object id -eq $ToolId
if (-not $tool) { throw "Unknown ToolId '$ToolId'. Valid: $($tools.id -join ', ')" }

$dyn = Join-Path $root ($tool.dyn -replace '/', '\')
if (-not (Test-Path -LiteralPath $dyn)) { throw ".dyn not found: $dyn" }

# Revit 2025 install location from registry (no hard-coded path)
$revitExe = $null
foreach ($k in Get-ChildItem 'HKLM:\SOFTWARE\Autodesk\Revit\2025*' -ErrorAction SilentlyContinue) {
  $loc = (Get-ItemProperty $k.PSPath -ErrorAction SilentlyContinue).InstallationLocation
  if ($loc -and (Test-Path (Join-Path $loc 'Revit.exe'))) { $revitExe = Join-Path $loc 'Revit.exe'; break }
}
if (-not $revitExe) {
  $cand = Join-Path $env:ProgramFiles 'Autodesk\Revit 2025\Revit.exe'
  if (Test-Path $cand) { $revitExe = $cand }
}
if (-not $revitExe) { throw 'Revit 2025 not found (registry and default path).' }

# VBScript string escaping: double any double-quote
function Q([string]$s) { '"' + ($s -replace '"', '""') + '"' }

$lines = @("' Generated by New-DynamoJournal.ps1 (POC, unverified)", 'Dim Jrn', 'Set Jrn = CrsJournalScript')

if (-not $SkipTemplate) {
  if (-not $Template) {
    $pd = Join-Path $env:ProgramData 'Autodesk\RVT 2025\Templates'
    $Template = Get-ChildItem $pd -Filter *.rte -Recurse -ErrorAction SilentlyContinue |
                Select-Object -First 1 -ExpandProperty FullName
  }
  if (-not $Template -or -not (Test-Path -LiteralPath $Template)) {
    throw 'No .rte template found; pass -Template or use -SkipTemplate.'
  }
  # Command text format copied from a local journal by the earlier session; locale-dependent.
  $lines += 'Jrn.Command "AccelKey" , "ID_REVIT_FILE_OPEN"'
  $lines += 'Jrn.Data "File Name" , "IDOK" , ' + (Q $Template)
}

# Safety: dynPathExecute=False, dynAutomation=False, dynForceManualRun=True -> no Run
$lines += 'Jrn.Command "Ribbon" , "Dynamo , ID_VISUAL_PROGRAMMING_DYNAMO"'
$lines += 'Jrn.Data "APIStringStringMapJournalData" , 5 , _'
$lines += '  "dynShowUI" , "True" , "dynAutomation" , "False" , _'
$lines += '  "dynPath" , ' + (Q $dyn) + ' , _'
$lines += '  "dynPathExecute" , "False" , "dynForceManualRun" , "True"'

$outDir = Join-Path $env:LOCALAPPDATA 'DynamoToolbox\journals'
New-Item -ItemType Directory -Force $outDir | Out-Null
$journal = Join-Path $outDir ("{0}_{1:yyyyMMdd_HHmmss}.txt" -f $ToolId, (Get-Date))
[IO.File]::WriteAllLines($journal, $lines, (New-Object Text.UTF8Encoding($true)))

Write-Host "Revit   : $revitExe"
Write-Host "Dyn     : $dyn"
Write-Host "Journal : $journal"

if ($Launch) {
  $running = Get-Process Revit -ErrorAction SilentlyContinue |
             Where-Object { $_.Path -and $_.Path -like '*Revit 2025*' }
  if ($running) {
    Write-Warning 'Revit 2025 is already running. Not starting a second instance (existing-instance path is P3).'
    return
  }
  Start-Process -FilePath $revitExe -ArgumentList ('"{0}"' -f $journal)
}
