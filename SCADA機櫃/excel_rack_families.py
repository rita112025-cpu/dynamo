def runtime_source() -> str:
    source = (ROOT / "scada_racks.py").read_text(encoding="utf-8")
    functions = {node.name: node for node in ast.parse(source).body if isinstance(node, ast.FunctionDef)}
    names = ("read_rows", "num", "shared_parameter_definitions", "run_transaction", "family_template_path",
             "family_name", "family_defaults", "add_family_parameters", "build_family", "build_families",
             "rack_values", "remove_backups")
    segments = []
    for name in names:
        segment = ast.get_source_segment(source, functions[name])
        if functions[name].decorator_list:
            segment = "@contextmanager\n" + segment
        if name == "family_name":
            segment = segment.replace('return "SCADA_機櫃_" + code', 'location = row["安裝位置"].strip()\n    station = re.fullmatch(r"Phase 1 (SB\\d+) Station", location)\n    if station:\n        label = station.group(1)\n    elif location == "Depot Administration Building - Telecom SCADA Equipment Room":\n        label = "機廠行政大樓_電信SCADA設備室"\n    elif location == "Depot - Administration Building - Computer Room (汐東雲平台)":\n        label = "機廠行政大樓_電腦房"\n    elif location == "Depot - TSS (機廠牽引變電站)":\n        label = "機廠TSS"\n    else:\n        raise Exception("無法判定族群檔名的安裝位置: " + repr(location))\n    return "SCADA_機櫃_" + code + "_" + label')
        segments.append(segment)
    result = RUNTIME_HEADER + "\n\n" + "\n\n\n".join(segments) + "\n" + RUNTIME_MAIN
    # Keep shared definitions isolated from the SoW job.
    result = result.replace('"SCADA_SoW_V6_SharedParameters.txt"', '"SCADA_Excel_SharedParameters.txt"')
    compile(result, "excel_rack_runtime.py", "exec")
    return result


def make_graph(source: str, csv_path: Path, family_dir: Path) -> dict:
    graph = json.loads((ROOT / "SCADA_Racks_SoW_V6.dyn").read_text(encoding="utf-8-sig"))
    inputs = [node for node in graph["Nodes"] if node["NodeType"] == "StringInputNode"][:2]
    script = next(node for node in graph["Nodes"] if "Code" in node)
    watch = next(node for node in graph["Nodes"] if node["ConcreteType"].startswith("CoreNodeModels.Watch,"))
    inputs[0]["InputValue"] = str(csv_path.resolve())
    inputs[1]["InputValue"] = str(family_dir.resolve())
    script["Inputs"] = script["Inputs"][:2]
    script["Code"] = source
    graph["Nodes"] = inputs + [script, watch]
    ports = {port["Id"] for node in graph["Nodes"] for key in ("Inputs", "Outputs") for port in node[key]}
    graph["Connectors"] = [link for link in graph["Connectors"] if link["Start"] in ports and link["End"] in ports]
    labels = dict(zip((node["Id"] for node in graph["Nodes"]),
                      ("Excel 轉換的設備 CSV", "RFA 與共用參數輸出資料夾", "建立含資訊的電氣設備族群", "執行結果")))
    graph["View"]["NodeViews"] = [view for view in graph["View"]["NodeViews"] if view["Id"] in labels]
    for view in graph["View"]["NodeViews"]:
        view["Name"] = labels[view["Id"]]
    graph.update(Uuid=str(uuid.uuid4()), Name="SCADA_Racks_Excel", Description="依機櫃規格與位置配置表產生逐台含資訊的 RFA")
    graph["View"]["Dynamo"]["RunType"] = "Manual"
    return graph


def prepare(workbook_path: Path, output: Path) -> list[dict[str, str]]:
    rows = read_equipment(workbook_path)
    source = runtime_source()
    csv_path = output / "SCADA_Racks_Excel.csv"
    graph = make_graph(source, csv_path, output / "族群")
    output.mkdir(parents=True, exist_ok=True)
    with csv_path.open("w", encoding="utf-8-sig", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=COLUMNS)
        writer.writeheader()
        writer.writerows(rows)
    (output / "excel_rack_runtime.py").write_text(source, encoding="utf-8")
    (output / "SCADA_Racks_Excel.dyn").write_text(json.dumps(graph, ensure_ascii=False, indent=2), encoding="utf-8")
    return rows


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workbook", type=Path, default=DEFAULT_WORKBOOK)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUTPUT)
    arguments = parser.parse_args()
    try:
        rows = prepare(arguments.workbook.resolve(), arguments.out.resolve())
    except (OSError, ValueError, ImportError, KeyError) as exc:
        print("準備失敗: " + str(exc), file=sys.stderr)
        return 1
    print(f"已準備 {len(rows)} 台設備；尚需在 Revit 執行 Dynamo 產生 RFA。")
    for size in sorted({row["尺寸"] for row in rows}):
        print(f"  {size} mm：{sum(row['尺寸'] == size for row in rows)} 台")
    print(arguments.out.resolve() / "SCADA_Racks_Excel.dyn")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
